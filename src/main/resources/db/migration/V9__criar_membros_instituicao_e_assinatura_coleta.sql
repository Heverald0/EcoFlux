CREATE TABLE tb_membros_instituicao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instituicao_id BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL,
    papel VARCHAR(30) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    data_vinculo TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_membro_instituicao_usuario UNIQUE (instituicao_id, usuario_id),
    CONSTRAINT fk_membro_instituicao FOREIGN KEY (instituicao_id) REFERENCES tb_instituicoes(id),
    CONSTRAINT fk_membro_usuario FOREIGN KEY (usuario_id) REFERENCES tb_usuarios(id)
);

